test('repeating actual native end and Session events cannot publish the same result twice', options, async t => {
  const r = await taskRunsFixture(t), ends = [], messages = []
  r.ctx.on('subagent/end', function (info) { ends.push({ info, carrier: this }) })
  r.ctx.on('session/event', function (session, event) { if (event.type === 'assistant/message') messages.push({ session, event, carrier: this }) })
  const receipt = await start(r)
  await r.settled(receipt.id); await r.chief.whenIdle()
  const original = await noticesOf(r, r.chief.id, receipt.id)
  assert.equal(original.length, 1)
  const end = await until(() => ends.find(item => item.info.id === receipt.sessionId), 'real subagent/end payload')
  const event = messages.find(item => item.session.id === receipt.sessionId)
  assert.ok(event, 'capture the actual worker Session event rather than inventing a result')
  for (let repeat = 0; repeat < 2; repeat++) {
    await r.ctx.parallel(end.carrier, 'subagent/end', end.info)
    await r.ctx.parallel(event.carrier, 'session/event', event.session, event.event)
  }
  await r.rt.save(); await r.ctx.sessions.flush(r.chief.session)
  const after = await noticesOf(r, r.chief.id, receipt.id)
  assert.deepEqual(after.map(message => message.id), original.map(message => message.id))
  assert.equal(r.rt.state.taskRuns[receipt.id].status, 'completed')
})

