test('actual newPart advances the originating background thread and completion reaches only its successor', options, async t => {
  const r = await taskRunsFixture(t)
  const heldChat = r.adapter.hold('chat'), heldWorker = r.adapter.hold('A')
  r.chief.followup(userMessage('ORIGINATING_THREAD_MARKER'))
  await r.adapter.started('chat')
  const receipt = await start(r)
  await r.adapter.started('A')
  await r.rt.newPart(r.chief.id)
  const foreground = r.rt.chatOf(r.ids.chief)
  assert.notEqual(foreground, r.chief.id)
  assert.ok(r.rt.botOf(r.ids.chief).openParts.some(part => part.sessionId === r.chief.id))
  heldChat.open(); await r.chief.whenIdle()
  await r.rt.newPart(r.chief.id)
  const successor = await until(() => {
    const target = threadCurrentOfPart(r.rt.botOf(r.ids.chief), r.chief.id)
    return target && target !== r.chief.id ? target : undefined
  }, 'actual background thread successor')
  assert.notEqual(successor, foreground)
  assert.equal(r.rt.state.taskRuns[receipt.id].status, 'running')
  heldWorker.open(); const terminal = await r.settled(receipt.id)
  assert.equal(terminal.notification.status, 'delivered'); assert.equal(terminal.notification.sessionId, successor)
  const notices = async sessionId => {
    const { events } = await r.ctx.sessionQuery.readSession(sessionId)
    const messages = events.flatMap(event => event.type === 'agent/inbox/spliced' ? event.data.inserted ?? [] : event.type === 'user/message' ? [event.data.message ?? event.data] : [])
    return [...new Map(messages.filter(message => message?.source?.taskRunId === receipt.id).map(message => [message.id, message])).values()]
  }
  assert.equal((await notices(successor)).length, 1)
  assert.equal((await notices(foreground)).length, 0)
  assert.equal((await notices(r.chief.id)).length, 0)
})

