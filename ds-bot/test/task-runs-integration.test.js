test('same-owner same-model same-label parallel attempts keep distinct Sessions and exact steer/cancel targets', options, async t => {
  const r = await taskRunsFixture(t), held = r.adapter.hold('A')
  const [a, b] = await Promise.all([start(r), start(r)])
  await until(() => r.adapter.calls.filter(call => call.model === 'A').length === 2, 'two actual requests to the same model')
  assert.notEqual(a.id, b.id); assert.notEqual(a.sessionId, b.sessionId)
  assert.equal(a.model, b.model); assert.equal(a.provider, b.provider); assert.equal(a.label, b.label)
  assert.equal(r.ctx.agents.get(a.sessionId).status, 'running'); assert.equal(r.ctx.agents.get(b.sessionId).status, 'running')
  await r.rt.taskRunControl(a.id, 'steer', 'SAME_MODEL_A_ONLY', { agent: r.chief })
  await Promise.all([r.ctx.sessions.flush(r.ctx.agents.get(a.sessionId).session), r.ctx.sessions.flush(r.ctx.agents.get(b.sessionId).session)])
  assert.ok(flattened((await r.rt.taskRunLog(a.id, { user: true })).events).includes('SAME_MODEL_A_ONLY'))
  assert.ok(!flattened((await r.rt.taskRunLog(b.id, { user: true })).events).includes('SAME_MODEL_A_ONLY'))
  await r.rt.taskRunControl(a.id, 'cancel', undefined, { agent: r.chief })
  assert.equal((await r.settled(a.id)).status, 'cancelled')
  assert.equal(r.rt.state.taskRuns[b.id].status, 'running'); assert.equal(r.ctx.agents.get(b.sessionId).status, 'running')
  held.open(); assert.equal((await r.settled(b.id)).status, 'completed')
})

test('an identical request retry reuses its retained receipt even after the original task directory disappears', options, async t => {
  const r = await taskRunsFixture(t), directory = join(r.project, 'retired-request-directory')
  await mkdir(directory)
  const args = { request_id: 'receipt-survives-directory', cwd: directory }
  const original = await start(r, args)
  await r.settled(original.id); await r.chief.whenIdle()
  assert.equal(await realpath(directory), directory, 'verify the exact isolated absolute directory before removal')
  await rm(directory, { recursive: true })
  await assert.rejects(access(directory), error => error.code === 'ENOENT')
  const [retryA, retryB] = await Promise.all([start(r, args), start(r, args)])
  assert.equal(retryA.id, original.id); assert.equal(retryB.id, original.id)
  assert.equal(retryA.sessionId, original.sessionId); assert.equal(retryA.status, 'completed')
  assert.equal(Object.keys(r.rt.state.taskRuns).length, 1)
  assert.equal(r.adapter.calls.filter(call => call.model === 'A').length, 1)
  await assert.rejects(access(directory), error => error.code === 'ENOENT')
})
