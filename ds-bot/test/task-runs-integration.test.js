  assert.equal((await r.rt.taskRunRead(child.id, { agent: parentAgent })).id, child.id)
  await assert.rejects(r.rt.taskRunRead(child.id, { agent: siblingAgent }), error => error.code === 'bot/task-unauthorized')
  await assert.rejects(r.rt.taskRunControl(sibling.id, 'cancel', undefined, { agent: parentAgent }), error => error.code === 'bot/task-unauthorized')
  await r.rt.taskRunControl(child.id, 'steer', 'ONLY_CHILD_INSTRUCTION', { agent: parentAgent })
